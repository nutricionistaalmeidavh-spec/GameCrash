import {NodeIO,getBounds} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {weld,simplify,dedup,prune,textureCompress} from '@gltf-transform/functions';
import {MeshoptSimplifier} from 'meshoptimizer';
import sharp from 'sharp';
import {writeFile} from 'node:fs/promises';
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS);
const doc=await io.read(process.argv[2]);
await MeshoptSimplifier.ready;
const prepared=process.argv.includes('--prepared');
await doc.transform(weld(),...(prepared?[]:[simplify({simplifier:MeshoptSimplifier,ratio:.25,error:.003})]),dedup(),prune(),textureCompress({encoder:sharp,targetFormat:'webp',resize:[1024,1024],quality:82}));
const scene=doc.getRoot().listScenes()[0],bounds=getBounds(scene);
const scale=4.8/(bounds.max[2]-bounds.min[2]);
const axleNodes=doc.getRoot().listNodes().filter(n=>/^(Wheel(Front|Rear)[LR]|concept-wheel-[0-3])$/.test(n.getName()));
const centerZ=axleNodes.reduce((s,n)=>s+n.getWorldTranslation()[2],0)/4;
const centerX=(bounds.min[0]+bounds.max[0])/2;
const root=doc.createNode('CarConcept_Normalized').setScale([scale,scale,scale]).setTranslation([-centerX*scale,-Math.min(...axleNodes.map(n=>getBounds(n).min[1]))*scale,-centerZ*scale]);
for(const child of scene.listChildren())root.addChild(child);scene.addChild(root);

const b=getBounds(scene),wheels=axleNodes.map(n=>({name:n.getName(),position:n.getWorldTranslation()}));
const front=wheels.filter(w=>w.name.includes('Front')||/concept-wheel-[13]/.test(w.name)),rear=wheels.filter(w=>w.name.includes('Rear')||/concept-wheel-[02]/.test(w.name));
const y=wheels.reduce((s,w)=>s+w.position[1],0)/4;
const track=wheels.filter(w=>w.position[0]>0).reduce((s,w)=>s+w.position[0],0)/2-wheels.filter(w=>w.position[0]<0).reduce((s,w)=>s+w.position[0],0)/2;
const radius=(getBounds(axleNodes[0]).max[1]-getBounds(axleNodes[0]).min[1])/2;
const triangles=doc.getRoot().listMeshes().reduce((s,m)=>s+m.listPrimitives().reduce((n,p)=>n+(p.getIndices()?.getCount()??p.getAttribute('POSITION').getCount())/3,0),0);
const parts=doc.getRoot().listNodes().filter(n=>n.getExtras().crashPart).map(n=>{const bounds=getBounds(n),id=n.getExtras().crashPart;return {id,center:bounds.min.map((v,i)=>(v+bounds.max[i])/2),half:bounds.min.map((v,i)=>Math.max(.015,(bounds.max[i]-v)/2)),mass:id.startsWith('glass')?3:id.startsWith('door')?24:id==='hood'?12:6,threshold:id.startsWith('glass')?.4:id.startsWith('door')?.60:id==='hood'?.30:.22}});
const metadata={parts,size:[b.max[0]-b.min[0],b.max[1]-b.min[1],4.8],wheelbase:(front[0].position[2]+front[1].position[2]-rear[0].position[2]-rear[1].position[2])/2,wheelRadius:radius,wheelTrack:track,wheelCenterY:y,triangles:Math.round(triangles),wheels};
for(const n of axleNodes){const p=n.getWorldTranslation();n.setName('concept-wheel-'+(p[0]<0?(p[2]<0?0:1):(p[2]<0?2:3)))}
await io.write('public/assets/concept/car.glb',doc);
await writeFile('src/game/concept.json',JSON.stringify(metadata,null,2)+'\n');console.log(metadata);
